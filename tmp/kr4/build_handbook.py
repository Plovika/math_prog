def el(tag,children=()):
    node=OxmlElement('m:'+tag)
    for c in children: node.append(c)
    return node

def run(text,roman=False):
    node=el('r')
    props=el('rPr')
    if roman:
        sty=el('sty');sty.set(qn('m:val'),'p');props.append(sty)
    node.append(props)
    wp=OxmlElement('w:rPr')
    fonts=OxmlElement('w:rFonts')
    fonts.set(qn('w:ascii'),'Cambria Math');fonts.set(qn('w:hAnsi'),'Cambria Math')
    wp.append(fonts)
    node.append(wp)
    t=el('t');t.text=text;t.set(qn('xml:space'),'preserve');node.append(t)
    return node

class MathParser:
    def __init__(self,text): self.s=text;self.i=0
    def seq(self,stop=None):
        nodes=[]
        while self.i<len(self.s):
            if stop and self.s[self.i]==stop:
                self.i+=1;break
            if self.s[self.i].isspace(): self.i+=1;continue
            if self.s[self.i] in '^_':
                marker=self.s[self.i];self.i+=1
                argument=self.argument()
                base=nodes.pop() if nodes else run('')
                if marker=='^' and base.tag==qn('m:sSub'):
                    obj=el('sSubSup',[deepcopy(base.find(qn('m:e'))),deepcopy(base.find(qn('m:sub'))),el('sup',argument)])
                elif marker=='_' and base.tag==qn('m:sSup'):
                    obj=el('sSubSup',[deepcopy(base.find(qn('m:e'))),el('sub',argument),deepcopy(base.find(qn('m:sup')))])
                else:
                    obj=el('sSup' if marker=='^' else 'sSub',[el('e',[base]),el('sup' if marker=='^' else 'sub',argument)])
                nodes.append(obj)
            else: nodes.extend(self.atom())
        return nodes
    def argument(self):
        while self.i<len(self.s) and self.s[self.i].isspace():self.i+=1
        if self.i<len(self.s) and self.s[self.i]=='{':
            self.i+=1;return self.seq('}')
        return self.atom()
    def raw_group(self):
        if self.i>=len(self.s) or self.s[self.i]!='{':return ''
        self.i+=1;start=self.i;depth=1
        while self.i<len(self.s):
            if self.s[self.i]=='{':depth+=1
            if self.s[self.i]=='}':depth-=1
            if depth==0:
                text=self.s[start:self.i];self.i+=1;return text
            self.i+=1
        raise ValueError('Unbalanced text group')
    def atom(self):
        if self.i>=len(self.s):return []
        c=self.s[self.i];self.i+=1
        if c=='{':return [el('box',[el('e',self.seq('}'))])]
        if c!='\\':return [run(c)]
        if self.i>=len(self.s):return [run('\\')]
        if not self.s[self.i].isalpha():
            c=self.s[self.i];self.i+=1
            return [run(' ' if c in ',;!' else ('‖' if c=='|' else c))]
        start=self.i
        while self.i<len(self.s) and self.s[self.i].isalpha():self.i+=1
        cmd=self.s[start:self.i]
        if cmd in ('left','right'):return []
        if cmd in ('frac','tfrac','binom'):
            num=self.argument();den=self.argument()
            frac=el('f',[el('num',num),el('den',den)])
            if cmd=='binom':
                fp=el('fPr');typ=el('type');typ.set(qn('m:val'),'noBar');fp.append(typ);frac.insert(0,fp)
                dp=el('dPr')
                for name,value in [('begChr','('),('endChr',')')]:
                    child=el(name);child.set(qn('m:val'),value);dp.append(child)
                return [el('d',[dp,el('e',[frac])])]
            return [frac]
        if cmd=='sqrt':
            props=el('radPr');hide=el('degHide');hide.set(qn('m:val'),'1');props.append(hide)
            return [el('rad',[props,el('deg'),el('e',self.argument())])]
        if cmd in ('widehat','overline'):
            props=el('accPr');char=el('chr');char.set(qn('m:val'),'̂' if cmd=='widehat' else '̅');props.append(char)
            return [el('acc',[props,el('e',self.argument())])]
        if cmd in ('text','mathrm','mathbf','operatorname'):
            if self.i<len(self.s) and self.s[self.i]=='{':return [run(self.raw_group(),True)]
            return self.argument()
        if cmd not in SYMBOLS:raise ValueError('Unsupported TeX command '+cmd)
        return [run(SYMBOLS[cmd],cmd in ('min','max','lim','ln','sin','cos','arccos','pmod'))]

def math_node(text):
    return el('oMath',MathParser(text).seq())

def add_inline(paragraph,text):
    for part in re.split(r'(\$[^$]+\$|\*\*[^*]+\*\*|`[^`]+`)',text):
        if not part:continue
        if part.startswith('$') and part.endswith('$'):
            paragraph._p.append(math_node(part[1:-1]))
        elif part.startswith('**'):
            paragraph.add_run(part[2:-2]).bold=True
        elif part.startswith('`'):
            r=paragraph.add_run(part[1:-1]);r.font.name='Consolas';r.font.size=Pt(10)
        else:paragraph.add_run(part)

def markdown(doc,text):
    # Split display formulas before parsing paragraphs, including multi-line formulas.
    for i,part in enumerate(re.split(r'\$\$(.*?)\$\$',text,flags=re.S)):
        if i%2:
            # Independent equalities are separate editable equations for legibility.
            pieces=re.split(r'\\qquad|\\quad(?=\s*(?:P\(|k|m|0))',part.strip())
            for piece in pieces:
                if not piece.strip():continue
                p=doc.add_paragraph(style='Equation')
                p._p.append(math_node(piece.strip().rstrip(',')))
        else:
            for block in re.split(r'\n\s*\n',part.strip()):
                if not block.strip():continue
                lines=block.strip().splitlines()
                for j,line in enumerate(lines):
                    if line.startswith('#'):
                        level=min(len(line)-len(line.lstrip('#')),3)
                        title=line.lstrip('#').strip()
                        title=re.sub(r'[^\w\s]','',title,flags=re.UNICODE)
                        p=doc.add_heading(title,level)
                    else:
                        if j==0 or lines[j-1].startswith('#'):p=doc.add_paragraph()
                        elif p.text:p.add_run(' ')
                        add_inline(p,line.strip())

